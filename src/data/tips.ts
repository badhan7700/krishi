export function getTipBySlug(slug: string): Tip | undefined {
  return tips.find((tip) => tip.slug === slug)
}

// 🔊 বাটন যে লেখাটা পড়ে শোনাবে
export function tipToSpeech(tip: Tip): string {
  const parts = [tip.title, tip.summary]
  for (const section of tip.sections) {
    parts.push(section.heading, ...section.points)
  }
  // প্রতিটা অংশের শেষে দাঁড়ি না থাকলে দাঁড়ি দিই, যাতে পড়ার সময় একটু থামে
  return parts
    .map((part) => (/[।?:!]$/.test(part) ? part : part + "।"))
    .join(" ")
}
